import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, blade = false) {
  await page.goto(blade ? 'http://127.0.0.1:8000/login' : '/login')
  await page.getByLabel('Email', { exact: true }).fill('admin@example.id')
  await page.getByLabel('Kata sandi', { exact: true }).fill('admin123')
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'OK', exact: true }).click()
  await expect(page).toHaveURL(/\/admin$/)
}

test('Nuxt headers sort globally and residents occupy separate lines', async ({ page }) => {
  await login(page)
  await page.route('**/backend/api/asrama/kamar?*', async route => {
    const response = await route.fetch()
    const data = await response.json()
    data.records.data[0].penghuni = [{ id: 999998, name: 'Nama Pertama' }, { id: 999999, name: 'Nama Kedua' }]
    await route.fulfill({ response, json: data })
  })
  await page.goto('/kamar')
  await page.evaluate(() => { document.documentElement.dataset.sortTest = 'same-document' })
  await page.getByRole('columnheader', { name: 'Kamar', exact: false }).getByRole('button').click()
  await expect(page.locator('tbody tr').first().locator('td').first()).toHaveText('301')
  await expect(page.getByRole('columnheader', { name: 'Kamar', exact: false })).toHaveAttribute('aria-sort', 'ascending')
  const people = page.locator('tbody tr').first().locator('.resident-name')
  await expect(people).toHaveCount(2)
  const boxes = await people.evaluateAll(elements => elements.map(element => element.getBoundingClientRect().top))
  expect(boxes[1]).toBeGreaterThan(boxes[0]!)
  await page.getByRole('button', { name: 'Berikutnya', exact: true }).click()
  await expect(page.locator('tbody tr').first().locator('td').first()).toHaveText('311')
  await page.getByRole('columnheader', { name: 'Kamar', exact: false }).getByRole('button').click()
  await expect(page.locator('tbody tr').first().locator('td').first()).toHaveText('526')
  await expect(page.getByText('1/8', { exact: true })).toBeVisible()
  await page.getByLabel('Baris per halaman', { exact: true }).selectOption('50')
  await page.getByLabel('Cari kamar', { exact: true }).fill('50')
  await expect(page.locator('tbody tr')).toHaveCount(9)
  for (const label of ['Lantai', 'Penghuni', 'Kapasitas', 'Status']) {
    const header = page.getByRole('columnheader', { name: label, exact: false })
    await header.getByRole('button').click()
    await expect(header).toHaveAttribute('aria-sort', 'ascending')
    await header.getByRole('button').click()
    await expect(header).toHaveAttribute('aria-sort', 'descending')
    await expect(header.getByRole('button')).toBeEnabled()
    await expect(page.getByLabel('Baris per halaman', { exact: true })).toHaveValue('50')
    await expect(page.getByLabel('Cari kamar', { exact: true })).toHaveValue('50')
  }
  await expect(page.locator('html')).toHaveAttribute('data-sort-test', 'same-document')
  await page.unrouteAll({ behavior: 'wait' })
})

test('Blade sorting retains search, page size, and the current document', async ({ page }) => {
  await login(page, true)
  await page.goto('http://127.0.0.1:8000/kamar?per_page=50&q=50')
  await page.evaluate(() => { document.documentElement.dataset.sortTest = 'same-document' })
  const table = page.locator('[data-async-table]')
  await table.getByRole('columnheader', { name: 'Kamar', exact: false }).getByRole('link').click()
  await expect(table.locator('tbody tr').first().locator('td').first()).toHaveText('501')
  await table.getByRole('columnheader', { name: 'Kamar', exact: false }).getByRole('link').click()
  await expect(table.locator('tbody tr').first().locator('td').first()).toHaveText('509')
  await expect(page.getByLabel('Baris per halaman', { exact: true })).toHaveValue('50')
  await table.getByRole('link', { name: 'Reset', exact: true }).click()
  await expect(table.locator('tbody tr').first().locator('td').first()).toHaveText('526')
  await expect(table.locator('tbody tr')).toHaveCount(50)
  await expect(page.locator('html')).toHaveAttribute('data-sort-test', 'same-document')
})

test('local tables sort dates and amounts in both directions', async ({ page }) => {
  await login(page, true)
  await page.goto('http://127.0.0.1:8000/pengumuman')
  await page.evaluate(() => { document.querySelector('#kamar')?.classList.remove('hidden') })
  const panel = page.locator('#kamar')
  await panel.getByRole('columnheader', { name: 'Tanggal Laundry', exact: false }).getByRole('button').click()
  await expect(panel.locator('tbody tr').first().locator('td').first()).toHaveText('01/01/2026')
  await panel.getByRole('columnheader', { name: 'Tanggal Laundry', exact: false }).getByRole('button').click()
  await expect(panel.locator('tbody tr').first().locator('td').first()).toHaveText('10/01/2026')
  await panel.getByRole('columnheader', { name: 'Besar Tagihan', exact: false }).getByRole('button').click()
  await expect(panel.locator('tbody tr').first().locator('td').nth(2)).toHaveText('Rp 7.000')
  await panel.getByRole('columnheader', { name: 'Besar Tagihan', exact: false }).getByRole('button').click()
  await expect(panel.locator('tbody tr').first().locator('td').nth(2)).toHaveText('Rp 35.000')
})
