import { test, expect } from '@playwright/test'

test('feedback modal supports success, failure, repeated actions, focus and dark mode', async ({ page }, testInfo) => {
  await page.route('**/backend/api/asrama/session', route => route.fulfill({ json: { user: { id: 9999, name: 'User uji', role: 'user', email: 'test@example.id' }, csrfToken: 'test-token' } }))
  await page.route('**/backend/api/asrama/user/izin-keluar**', async route => {
    if (route.request().method() === 'POST') {
      if (route.request().postDataJSON().alasan === 'invalid') return route.fulfill({ status: 422, json: { errors: { alasan: ['Alasan tidak valid.'] } } })
      return route.fulfill({ status: 201, json: { message: 'Izin keluar berhasil diajukan.' } })
    }
    return route.fulfill({ json: { records: { data: [], current_page: 1, last_page: 1 } } })
  })
  await page.route('**/backend/api/asrama/user/kamar', route => route.fulfill({ json: { room: null, history: [] } }))
  await page.route('**/backend/api/asrama/user/keluhan**', route => route.fulfill({ json: { records: { data: [], current_page: 1, last_page: 1 } } }))
  await page.goto('/user/kamar')
  const section = page.getByRole('region', { name: 'Izin keluar', exact: true })
  const submit = section.getByRole('button', { name: 'Ajukan izin', exact: true })
  async function fill(alasan: string) {
    await section.getByLabel('Waktu keluar (WIB)', { exact: true }).fill('2026-10-14T08:00')
    await section.getByLabel('Waktu kembali (WIB)', { exact: true }).fill('2026-10-14T18:00')
    await section.getByLabel('Alasan', { exact: true }).fill(alasan)
  }
  await fill('Keluarga')
  await submit.click()
  const dialog = page.getByRole('dialog', { name: 'Berhasil diajukan', exact: true })
  await expect(dialog).toBeVisible()
  const lightBackground = await dialog.evaluate(element => getComputedStyle(element).backgroundColor)
  await dialog.screenshot({ path: testInfo.outputPath('feedback-success.png') })
  const ok = dialog.getByRole('button', { name: 'OK', exact: true })
  await expect(ok).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => document.querySelector('dialog[open]')?.contains(document.activeElement))).toBe(true)
  await ok.click()
  await expect(dialog).toBeHidden()
  await expect(submit).toBeFocused()
  await page.locator('[data-theme-toggle]').click()
  await fill('invalid')
  await submit.click()
  const failed = page.getByRole('dialog', { name: 'Gagal', exact: true })
  await expect(failed).toContainText('Alasan tidak valid.')
  await expect(page.locator('html')).toHaveClass(/dark/)
  expect(await failed.evaluate(element => getComputedStyle(element).backgroundColor)).not.toBe(lightBackground)
  await failed.screenshot({ path: testInfo.outputPath('feedback-error.png') })
  await page.keyboard.press('Escape')
  await expect(failed).toBeHidden()
  await expect(section.getByLabel('Alasan', { exact: true })).toHaveValue('invalid')
  await fill('Keluarga')
  await submit.click()
  await expect(dialog).toBeVisible()
  await ok.click()
  await expect(dialog).toBeHidden()
  await page.unrouteAll({ behavior: 'wait' })
})

test('Blade login errors appear in modal with OK and safe text rendering', async ({ page }) => {
  await page.goto('http://127.0.0.1:8000/login')
  await page.getByLabel('Email', { exact: true }).fill('user1@example.id')
  await page.getByLabel('Kata sandi', { exact: true }).fill('incorrect-password')
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Gagal', exact: true })
  await expect(dialog).toContainText('Email atau kata sandi tidak sesuai.')
  await expect(dialog.getByRole('button', { name: 'OK', exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.evaluate(() => (window as any).AsramaFeedback.show('<script>window.injected = true</script>'))
  await expect(page.getByRole('dialog', { name: 'Berhasil', exact: true })).toContainText('<script>window.injected = true</script>')
  expect(await page.evaluate(() => (window as any).injected)).toBeUndefined()
  await page.getByRole('dialog').getByRole('button', { name: 'OK', exact: true }).click()
})
